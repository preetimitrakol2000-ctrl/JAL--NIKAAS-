// Helper to generate 72 hours of persistent historical telemetry points (one per hour)
function generate72HourTelemetry(
  baseFarm: number,
  baseDown: number,
  baseVelocity: number,
  baseDischarge: number,
  profile: 'STABLE' | 'BLOCKAGE' | 'BACKFLOW' | 'SURGING' | 'FAULT'
): TelemetryPoint[] {
  const points: TelemetryPoint[] = [];
  const now = Date.now();

  for (let i = 72; i >= 0; i--) {
    const timestamp = new Date(now - i * 3600 * 1000).toISOString();
    let farm = baseFarm;
    let down = baseDown;
    let vel = baseVelocity;
    let discharge = baseDischarge;
    let rain = 0;

    const hourFromStart = 72 - i;

    if (profile === 'BLOCKAGE') {
      // Steady until 24 hours ago, then debris accumulates: upstream farm level rises, velocity and discharge drop
      if (hourFromStart > 44) {
        const factor = (hourFromStart - 44) / 28; // 0 to 1
        farm = baseFarm + factor * 26.5 + Math.sin(i * 0.4) * 1.5;
        down = baseDown - factor * 8.2 + Math.cos(i * 0.4) * 1.2;
        vel = Math.max(0.04, baseVelocity - factor * 0.52);
        discharge = Math.max(30, baseDischarge - factor * 380);
        rain = hourFromStart > 40 && hourFromStart < 54 ? 4.5 : 0;
      } else {
        farm = baseFarm - 18 + Math.sin(i * 0.2) * 2;
        down = baseDown + Math.cos(i * 0.2) * 1.5;
        vel = baseVelocity;
        discharge = baseDischarge;
      }
    } else if (profile === 'BACKFLOW') {
      // High-tide river lock cycles every 12 hours
      const tidalCycle = Math.sin((hourFromStart * Math.PI) / 6);
      down = baseDown + tidalCycle * 14.5;
      farm = baseFarm + Math.max(0, tidalCycle * 4.2);
      if (down > farm) {
        vel = -0.18 * Math.abs(tidalCycle);
        discharge = -120 * Math.abs(tidalCycle);
      } else {
        vel = Math.max(0.2, 0.45 * (1 - Math.abs(tidalCycle)));
        discharge = Math.max(80, 280 * (1 - Math.abs(tidalCycle)));
      }
    } else if (profile === 'SURGING') {
      // Heavy monsoon rain surge peaking 14 hours ago
      if (hourFromStart > 48) {
        farm = baseFarm + Math.sin((hourFromStart - 48) * 0.2) * 18 + 12;
        down = baseDown + Math.sin((hourFromStart - 48) * 0.2) * 14 + 10;
        vel = Math.min(1.35, baseVelocity + 0.45);
        discharge = baseDischarge + 420;
        rain = hourFromStart < 62 ? 8.4 : 1.2;
      } else {
        farm = baseFarm - 8 + Math.sin(i * 0.2) * 2;
        down = baseDown - 6 + Math.cos(i * 0.2) * 2;
        vel = baseVelocity;
        discharge = baseDischarge;
      }
    } else if (profile === 'FAULT') {
      if (hourFromStart > 60) {
        farm = 0; // Fault / dropped signal
        vel = 0;
        discharge = 0;
      } else {
        farm = baseFarm + Math.sin(i * 0.3) * 2;
        vel = baseVelocity;
        discharge = baseDischarge;
      }
      down = baseDown + Math.cos(i * 0.3) * 1.5;
    } else {
      // STABLE
      farm = baseFarm + Math.sin(i * 0.25) * 2.2;
      down = baseDown + Math.cos(i * 0.25) * 1.8;
      vel = baseVelocity + Math.sin(i * 0.3) * 0.05;
      discharge = baseDischarge + Math.sin(i * 0.3) * 35;
      rain = Math.random() > 0.85 ? 1.5 : 0;
    }

    const diff = Number((farm - down).toFixed(1));

    points.push({
      timestamp,
      farmLevel: Number(farm.toFixed(1)),
      downstreamLevel: Number(down.toFixed(1)),
      differential: diff,
      flowVelocityMs: Number(vel.toFixed(2)),
      dischargeLs: Math.round(discharge),
      rainfallMm: Number(rain.toFixed(1)),
    });
  }

  return points;
}

